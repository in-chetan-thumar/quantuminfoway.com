if (!function_exists('case_studies_hub_groups')) {
    /**
     * Hub cards grouped by product (dual platforms share one card).
     * @return list<array{group:string,title:string,industry:string,tagline:string,hero:string,web:?array,mobile:?array,single:?array}>
     */
    function case_studies_hub_groups(): array
    {
        $groups = [];
        foreach (case_studies_all() as $cs) {
            $g = $cs['hub_group'];
            if (!isset($groups[$g])) {
                $groups[$g] = [
                    'group' => $g,
                    'title' => $cs['hub_title'],
                    'industry' => $cs['industry'],
                    'tagline' => '',
                    'hero' => $cs['hero_image'],
                    'web' => null,
                    'mobile' => null,
                    'single' => null,
                ];
            }
            if ($cs['platform'] === 'web') {
                $groups[$g]['web'] = $cs;
                $groups[$g]['hero'] = $cs['hero_image'];
                $groups[$g]['tagline'] = $cs['tagline'];
            } elseif ($cs['platform'] === 'mobile') {
                $groups[$g]['mobile'] = $cs;
                if ($groups[$g]['tagline'] === '') {
                    $groups[$g]['tagline'] = $cs['tagline'];
                }
            } else {
                $groups[$g]['single'] = $cs;
                $groups[$g]['hero'] = $cs['hero_image'];
                $groups[$g]['tagline'] = $cs['tagline'];
            }
        }
        return array_values($groups);
    }
