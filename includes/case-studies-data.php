if (!function_exists('case_study_get')) {
    function case_study_get(string $slug): ?array
    {
        $all = case_studies_all();
        if (!isset($all[$slug])) {
            return null;
        }
        $cs = $all[$slug];
        require_once __DIR__ . '/case-studies-narratives.php';
        $narratives = case_study_narratives();
        if (isset($narratives[$slug])) {
            $cs = array_merge($cs, $narratives[$slug]);
        }
        return $cs;
    }
}

